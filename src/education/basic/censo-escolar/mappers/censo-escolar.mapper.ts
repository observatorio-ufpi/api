@Injectable()
export class CensoEscolarMapper {
  mapToStandardFormat(data: any[], context: any): any {
    const { dimensions, filterParams } = context;

    if (dimensions.length > 0) {
      const result = data.map((item) => {
        const responseItem: any = {
          NO_ENTIDADE: item.NO_ENTIDADE,
          ANO: item.ANO,
          CO_MUNICIPIO: item.CO_MUNICIPIO,
          NO_MUNICIPIO: item.NO_MUNICIPIO,
          SG_UF: item.SG_UF,
          CO_ENTIDADE: item.CO_ENTIDADE,
          TP_DEPENDENCIA: item.TP_DEPENDENCIA,
          TP_LOCALIZACAO: item.TP_LOCALIZACAO,
        };

        dimensions.forEach((dim) => {
          if (categoryFields[dim]) {
            categoryFields[dim].forEach((field) => {
              responseItem[field] = item[field];
            });
          }
        });

        return responseItem;
      });

      return {
        result,
        metadata: {
          filters: filterParams,
          dimensions,
        },
      };
    }

    return {
      result: data,
      metadata: {
        filters: filterParams,
        dimensions,
      },
    };
  }
}
